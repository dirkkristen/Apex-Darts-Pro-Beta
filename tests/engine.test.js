const test=require('node:test');
const assert=require('node:assert/strict');
const E=require('../www/js/engine.js');
const C=require('../www/js/checkout.js');
const players=[{id:'a',name:'Alice'},{id:'b',name:'Bob'}];
const throw3=(m,seq)=>seq.map(([n,mult])=>E.throwDart(m,{n,mult}));

test('90 offers a legal two-dart finish and a three-dart alternative',()=>{
 const advice=C.advice(90,3,true);
 assert.equal(advice.type,'checkout');assert.equal(advice.text,'T18 → D18');
 assert.equal(advice.alternatives.some(r=>r.map(d=>d.code).join('-')==='T20-S10-D10'),false); // routes favour shortest first; valid path is still generated by enumeration
 assert.ok(C.finishes(90,3,true).every(r=>r.reduce((v,d)=>v+d.value,0)===90));
});
test('170,167,100,41,32 checkout routes',()=>{
 for(const [score,expected] of [[170,'T20 → T20 → DB'],[167,'T20 → T19 → DB'],[100,'T20 → D20'],[41,'S1 → D20'],[32,'D16']])assert.equal(C.advice(score,3,true).text,expected);
});
test('bogey number 169 has setup advice rather than checkout',()=>{assert.equal(C.advice(169,3,true).type,'setup');assert.ok(C.advice(90,1,true).text.includes('leave'));});
test('basic X01 finish, reverse on bust, and double-in',()=>{
 const m=E.create({mode:'x01',config:{startScore:101,doubleIn:true,doubleOut:true},players:[players[0]]});
 E.throwDart(m,{n:20,mult:1});assert.equal(m.players[0].score,101);
 E.throwDart(m,{n:20,mult:2});assert.equal(m.players[0].score,61);assert.equal(m.players[0].open,true);
 E.throwDart(m,{n:20,mult:3});assert.equal(m.players[0].score,101); // leaving 1 in double-out is an immediate bust
});
test('X01 bust restores the beginning of turn and advances',()=>{
 const m=E.create({mode:'x01',config:{startScore:90,doubleOut:true},players});
 E.throwDart(m,{n:20,mult:3});assert.equal(m.players[0].score,30);
 E.throwDart(m,{n:20,mult:3});assert.equal(m.players[0].score,90);assert.equal(m.current,1);assert.equal(m.players[0].stats.scored,0);
});
test('X01 works with real 90 checkout',()=>{const m=E.create({mode:'x01',config:{startScore:90,doubleOut:true},players:[players[0]]});E.throwDart(m,{n:18,mult:3});E.throwDart(m,{n:18,mult:2});assert.equal(m.finished,true);assert.deepEqual(m.winners,['a']);});
test('Circuit clears triple and finishes any bull',()=>{
 const m=E.create({mode:'circuit',config:{circuitLength:1},players:[players[0]]});E.throwDart(m,{n:1,mult:3});assert.equal(m.players[0].target,2);E.throwDart(m,{n:25,mult:1});assert.equal(m.finished,true);
});
test('XLD single double triple are distinct',()=>{
 const m=E.create({mode:'xld',config:{xldStart:1,xldEnd:1,xldFinish:'inner'},players:[players[0]]});
 throw3(m,[[1,1],[1,2],[1,3]]);assert.equal(m.players[0].target,2);E.throwDart(m,{n:25,mult:1});assert.equal(m.finished,false);E.throwDart(m,{n:25,mult:2});assert.equal(m.finished,true);
});
test('Cricket scores excess marks only while opponent open',()=>{
 const m=E.create({mode:'cricket',config:{cricketVariant:'standard'},players});
 E.throwDart(m,{n:20,mult:3});throw3(m,[[1,1],[1,1]]);assert.equal(m.current,1);
 throw3(m,[[19,1],[19,1],[19,1]]);assert.equal(m.current,0);
 E.throwDart(m,{n:20,mult:2});assert.equal(m.players[0].score,40);
});
test('Killer requires multiple players',()=>{assert.throws(()=>E.create({mode:'killer',players:[players[0]]}),/at least 2/);const m=E.create({mode:'killer',players});assert.notEqual(m.players[0].assigned,m.players[1].assigned);});
test('Shanghai advances only after every player has completed a visit',()=>{
 const m=E.create({mode:'shanghai',config:{shanghaiRounds:7},players});throw3(m,[[1,1],[1,1],[1,1]]);assert.equal(m.round,1);throw3(m,[[1,1],[1,1],[1,1]]);assert.equal(m.round,2);
});
test('Shanghai instant win on S/D/T',()=>{const m=E.create({mode:'shanghai',players:[players[0]]});throw3(m,[[1,1],[1,2],[1,3]]);assert.equal(m.finished,true);});
test('Neon Sniper only chooses 1..20',()=>{for(let i=0;i<80;i++){const m=E.create({mode:'sniper',players:[players[0]]});assert.ok(m.players[0].target>=1&&m.players[0].target<=20);}});
test('Bob27 scoring and penalty',()=>{const m=E.create({mode:'bob27',players:[players[0]]});throw3(m,[[0,1],[0,1],[0,1]]);assert.equal(m.players[0].score,25);assert.equal(m.players[0].target,2);E.throwDart(m,{n:2,mult:2});assert.equal(m.players[0].score,29);});
test('Halve-It halves accumulated score when a round is missed',()=>{const m=E.create({mode:'halveit',players:[players[0]]});throw3(m,[[20,1],[20,2],[20,3]]);assert.equal(m.players[0].score,120);throw3(m,[[0,1],[0,1],[0,1]]);assert.equal(m.players[0].score,60);});
test('Count-Up adds full scored face values',()=>{const m=E.create({mode:'countup',players:[players[0]]});throw3(m,[[20,3],[20,3],[20,3]]);assert.equal(m.players[0].score,180);assert.equal(m.round,2);});
test('Bingo creates a row',()=>{const m=E.create({mode:'bingo',players:[players[0]]});E.throwDart(m,{n:20,mult:3});E.throwDart(m,{n:16,mult:2});E.throwDart(m,{n:25,mult:2});assert.equal(m.finished,true);});
test('Gauntlet stages progress in order',()=>{const m=E.create({mode:'gauntlet',players:[players[0]]});E.throwDart(m,{n:16,mult:2});assert.equal(m.players[0].stage,0);E.throwDart(m,{n:20,mult:1});assert.equal(m.players[0].stage,1);});
test('Undo snapshots are independent from mutations',()=>{const m=E.create({mode:'x01',players});const before=E.clone(m);E.throwDart(m,{n:20,mult:3});assert.equal(before.players[0].score,501);});

test('X01 best-of-three legs resets the board and tracks winner',()=>{
 const m=E.create({mode:'x01',config:{startScore:101,doubleOut:true,bestOfLegs:3},players});
 // First leg, score 101 via T17+DB.
 E.throwDart(m,{n:17,mult:3});E.throwDart(m,{n:25,mult:2});
 assert.equal(m.finished,false);assert.equal(m.legNumber,2);assert.equal(m.players[0].legsWon,1);assert.equal(m.players[0].score,101);
 // Rotate opening player; complete guest visit.
 throw3(m,[[0,1],[0,1],[0,1]]);
 E.throwDart(m,{n:17,mult:3});E.throwDart(m,{n:25,mult:2});
 assert.equal(m.finished,true);assert.deepEqual(m.winners,['a']);
});
